# -*- coding: utf-8 -*-
"""Сопоставление названия лота с фразами номенклатуры.

Функции из src/utils/classifier.py: порядок слов и падежи не важны, марки с
цифрами и дефисом сравниваются точно, пунктуация площадок не мешает.

Все тесты офлайн: сеть и браузер не используются.

Запуск:
    pytest tests/test_nomenclature_match.py -v
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.utils.classifier import matches_nomenclature, nomenclature_hits  # noqa: E402


# ── 1. Порядок слов и падежные окончания ────────────────────────────────────


def test_порядок_слов_не_важен():
    """«Клиновая задвижка» обязана совпасть с лотом «Задвижки клиновые,
    фланцевые» — иначе фильтр потеряет позицию из-за порядка слов."""
    name = "Задвижки клиновые, фланцевые"
    assert matches_nomenclature(name, ["Клиновая задвижка"]) is True
    assert nomenclature_hits(name, ["Клиновая задвижка"]) == ["Клиновая задвижка"]


def test_регистр_не_важен():
    """Названия лотов приходят вразнобой capitals/low — сравнение нормализовано."""
    assert matches_nomenclature("НАСОС ЦЕНТРОБЕЖНЫЙ", ["Насос центробежный"]) is True


def test_ё_приводится_к_е():
    """«Ё» в названии не должна рвать совпадение с фразой через «Е»."""
    assert matches_nomenclature("ЁМКОСТЬ для масла", ["Емкость для масла"])


def test_все_слова_фразы_обязательны():
    """Одно слово из двух — не совпадение: половина фразы не наша номенклатура."""
    assert matches_nomenclature("Насос центробежный", ["Насос шестеренный"]) is False


# ── 2. Кавычки и дефис ───────────────────────────────────────────────────────


def test_кавычки_не_мешают_совпадению():
    """Кавычки в названии заменяются пробелом, а не склеивают слова."""
    assert matches_nomenclature("Поставка «НШ 1-15»", ["НШ 1-15"]) is True
    assert matches_nomenclature("Кабель „силовой“", ["Кабель силовой"]) is True


def test_дефис_значащий_в_марке():
    """«НШ 1-15» — марка, «1-15» не должна совпадать с «1-16»."""
    assert matches_nomenclature("НШ 1-15", ["НШ 1-15"]) is True
    assert matches_nomenclature("НШ 1-16", ["НШ 1-15"]) is False


# ── 3. Пустые и нестроковые значения ────────────────────────────────────────


def test_пустое_имя_не_совпадает():
    """Пустое имя / None / не-строка → False, без исключений."""
    assert matches_nomenclature("", ["Насос центробежный"]) is False
    assert matches_nomenclature(None, ["Насос центробежный"]) is False
    assert matches_nomenclature(123, ["Насос центробежный"]) is False


def test_пустые_фразы_не_совпадают():
    """Нет фраз или одни пустые — списка совпадений нет."""
    assert nomenclature_hits("Насос центробежный", []) == []
    assert nomenclature_hits("Насос центробежный", ["", "   "]) == []
    assert matches_nomenclature("Насос центробежный", []) is False


def test_hits_возвращают_все_совпавшие_фразы():
    """Совпало несколько фраз — возвращаются все, в исходном виде и порядке."""
    name = "Кабель силовой, провод медный"
    hits = nomenclature_hits(name, ["Провод медный", "Кабель силовой"])
    assert hits == ["Провод медный", "Кабель силовой"]


# ── 4. Нет ложных совпадений ────────────────────────────────────────────────


def test_стройка_не_совпадает_с_поставкой():
    """«Строительство дороги» ≠ «Насос центробежный»."""
    assert matches_nomenclature("Строительство дороги", ["Насос центробежный"]) is False


class TestЛожныеСовпадения:
    """Морфология по префиксу была слишком щедрой — «Фильтр-пресс» ловил
    любой фильтр."""

    def test_составное_через_дефис_только_целиком(self):
        assert not matches_nomenclature("Фильтр воздушный для компрессора", ["Фильтр-пресс"])
        assert not matches_nomenclature("Фильтр обеззоленный синяя лента", ["Фильтр-пресс"])
        assert matches_nomenclature("Поставка фильтр-пресса ФПАКМ", ["Фильтр-пресс"])

    def test_короткое_слово_только_точно(self):
        from src.utils.classifier import _word_matches

        assert not _word_matches("пачук", "пачки")
        assert not _word_matches("сода", "содержание")
        assert _word_matches("пачук", "пачук")

    def test_падежи_по_прежнему_ловятся(self):
        from src.utils.classifier import _word_matches

        for phrase_word, name_word in (
            ("центробежный", "центробежного"),
            ("задвижка", "задвижки"),
            ("подшипник", "подшипника"),
            ("клиновая", "клиновые"),
        ):
            assert _word_matches(phrase_word, name_word), (phrase_word, name_word)

    def test_похожий_корень_не_считается_своим(self):
        from src.utils.classifier import _word_matches

        assert not _word_matches("известь", "изверженный")


# ── 5. Пунктуация и служебные префиксы площадок ─────────────────────────────
#
# Названия лотов приходят не «чистыми»: площадки лепят к слову скобку
# («Мониторинг цен (подшипник на ось 2,1х3,6)»), а закупочные операторы —
# служебный номер через дефис («2608-Лента транспортерная/ АО «Ромашка»»).
# Раньше такое слово не совпадало ни с чем: скобка приклеивалась к слову, а
# «2608-Лента» разбиралось как составное через дефис и требовало, чтобы у
# фразы тоже было две части.


def test_скобка_не_мешает_совпадению():
    assert nomenclature_hits(
        "Мониторинг цен (подшипник на ось 2,1х3,6) для бюджета", ["подшипник"]
    ) == ["подшипник"]


def test_запятая_и_точка_не_приклеиваются_к_слову():
    assert nomenclature_hits("Насосы шламовые, запасные части.", ["шламовый насос"])


def test_служебный_номер_оператора_отделяется_от_слова():
    assert nomenclature_hits(
        "2608-Лента транспортерная/ АО «Ромашка»", ["лента транспортерная"]
    ) == ["лента транспортерная"]


def test_код_процедуры_с_дефисом_не_мешает():
    assert nomenclature_hits(
        "RUZVZ-8260, закупка Задвижки по заявке", ["задвижка"]
    ) == ["задвижка"]


def test_марка_с_дефисом_по_прежнему_точная():
    # «НШ 1-15» и «НШ 1-16» — разные насосы, путать их нельзя.
    assert nomenclature_hits("Насос шестеренный НШ 1-16", ["нш 1-15"]) == []
    assert nomenclature_hits("Насос шестеренный НШ 1-15", ["нш 1-15"]) == ["нш 1-15"]


def test_составное_слово_через_дефис_по_прежнему_сравнивается_по_частям():
    # Регрессия: «фильтр-пресс» ловил любой фильтр.
    assert nomenclature_hits("Фильтр воздушный КамАЗ", ["фильтр-пресс"]) == []
    assert nomenclature_hits("Запчасти к фильтр-прессу CPF 3000", ["фильтр-пресс"])


def test_подчёркивание_отделяет_слово():
    assert nomenclature_hits("Заявка СУ01-004622_запчасти Shantui_для ООО", ["shantui"])


def test_номер_заявки_не_приклеивается():
    # «ТЗ №7 ИТИС поставка запасных частей» — знак номера липнет к цифре и
    # к слову, и без чистки «№7» оставалось одним токеном.
    assert nomenclature_hits("ТЗ №7 ИТИС поставка запасных частей", ["запасных частей"])


def test_короткое_окончание_требует_своей_формы_в_справочнике():
    """«части» и «частей» общей основы в пять букв не дают — это не ошибка.

    Порог основы в пять символов защищает от «известь» ↔ «изверженный».
    Плата за него — формы вроде «запасных частей» приходится заводить в
    справочник отдельной строкой.
    """
    assert nomenclature_hits("поставка запасных частей", ["запасные части"]) == []
    assert nomenclature_hits("поставка запасных частей", ["запасных частей"])


def test_зч_через_дробь_склеивается_в_одно_слово():
    """«з/ч» и «з\\ч» — запчасти. Раньше дробь заменялась пробелом и от них
    оставались две буквы, которые совпадали с чем угодно."""
    assert nomenclature_hits("Гаражное об-е и з/ч для цеха", ["ЗЧ"]) == ["ЗЧ"]
    assert nomenclature_hits("ТМЦ з\\ч к карьерн.техн.свыше 20тн", ["ЗЧ"]) == ["ЗЧ"]
    assert nomenclature_hits("Инв. № З-00002896, ч. 2", ["ЗЧ"]) == []
