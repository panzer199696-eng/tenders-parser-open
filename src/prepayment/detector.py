"""
Определение условий предоплаты (задачи T034–T036).

Предоплата — весомый плюс при отборе: она снимает кассовый разрыв на закупке
у поставщика. Но программа видит только то, что площадка написала в тексте
лота; полные условия оплаты лежат во вложениях к документации, и разбор
вложений — следующий этап (31.08.2026).

Отсюда три состояния, а не два:

    yes      — в тексте прямо сказано об авансе или предоплате;
    no       — прямо сказано, что аванса нет (постоплата, отсрочка);
    unknown  — в тексте про оплату ничего нет.

**`unknown` никогда не выдаётся за `no`.** Это требование спецификации
(FR-012) и вопрос доверия к программе: «мы не знаем» и «предоплаты нет» —
разные вещи, и человек, увидев второе вместо первого, зря пропустит лот.

Порядок проверки важен: отрицание сильнее упоминания. Фраза «аванс не
предусмотрен» содержит слово «аванс», и без приоритета отрицаний лот
получил бы `yes` — ровно наоборот действительности.
"""

from __future__ import annotations

import re

# Прямой отказ от аванса. Проверяется ПЕРВЫМ: эти фразы содержат слова из
# положительного списка («аванс», «предоплата») и без приоритета дали бы
# обратный ответ.
NEGATIVE_PATTERNS = (
    r"аванс(?:овый платёж|овый платеж|а|ы)?\s+не\s+(?:предусмотрен|преду?смотрена|выплачивается|производится)",
    r"без\s+аванс",
    r"без\s+предоплат",
    r"предоплата\s+не\s+(?:предусмотрена|производится)",
    r"постоплат",
    r"оплата\s+по\s+факту",
    r"оплата\s+после\s+(?:поставки|отгрузки|подписания)",
    r"отсрочк[аи]\s+платежа",
    # Живая формулировка с площадки (26.08.2026):
    # «оплатить … в срок не позднее 15 рабочих дней с даты предоставления
    # отгрузочных документов». Слов «постоплата» и «отсрочка» здесь нет,
    # а по сути это оплата после поставки — самый частый вид условий.
    r"оплат\w*[^.]{0,120}?(?:в течение|в срок|не\s+позднее)[^.]{0,40}?дн\w*[^.]{0,80}?"
    r"(?:с\s+даты|после|с\s+момента)[^.]{0,60}?"
    r"(?:поставк|отгрузк|получени|подписани|предоставлени|приёмк|приемк|накладн|документ|счет|счёт|акт)",
)

# Признаки предоплаты.
POSITIVE_PATTERNS = (
    r"\bаванс",
    r"предоплат",
    r"предварительн\w*\s+оплат",
    r"\d{1,3}\s*%\s*(?:предоплат|аванс)",
    r"оплата\s+до\s+(?:поставки|отгрузки)",
)

PREPAYMENT_YES = "yes"
PREPAYMENT_NO = "no"
PREPAYMENT_UNKNOWN = "unknown"


def _compile(patterns) -> list[re.Pattern]:
    return [re.compile(p, re.IGNORECASE) for p in patterns]


_NEGATIVE = _compile(NEGATIVE_PATTERNS)
_POSITIVE = _compile(POSITIVE_PATTERNS)


def _quote(text: str, match: re.Match) -> str:
    """Кусок текста вокруг находки — чтобы человек мог проверить вывод.

    Программа не должна требовать веры на слово: рядом с пометкой всегда
    показывается фраза, по которой она решила.
    """
    start = max(0, match.start() - 40)
    end = min(len(text), match.end() + 40)
    fragment = text[start:end].replace("\n", " ").strip()
    return f"…{fragment}…" if start or end < len(text) else fragment


def detect(*parts: str) -> tuple[str, str]:
    """Состояние предоплаты и цитата, по которой оно определено.

    Принимает любые куски текста лота: название, описание, дополнительную
    информацию. Пустые пропускаются.
    """
    text = " ".join(str(p) for p in parts if p and str(p).strip())
    if not text.strip():
        return PREPAYMENT_UNKNOWN, ""

    for pattern in _NEGATIVE:
        found = pattern.search(text)
        if found:
            return PREPAYMENT_NO, _quote(text, found)

    for pattern in _POSITIVE:
        found = pattern.search(text)
        if found:
            return PREPAYMENT_YES, _quote(text, found)

    return PREPAYMENT_UNKNOWN, ""


def describe(state: str) -> str:
    """Состояние словами — для ленты, карточки и отчётов."""
    return {
        PREPAYMENT_YES: "предоплата",
        PREPAYMENT_NO: "без предоплаты",
    }.get(state, "условие не найдено")


def sort_bonus(state: str) -> int:
    """Насколько поднять лот в ленте (FR-013).

    Предоплата — весомый плюс, но не единственный критерий: лоты без неё
    остаются в работе, поэтому бонус сопоставим с одной группой номенклатуры,
    а не перевешивает профиль целиком.
    """
    return 10 if state == PREPAYMENT_YES else 0
