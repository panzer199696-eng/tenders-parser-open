def _norm(text: str) -> str:
    return text.lower().replace("ё", "е")


def assign_tags(name: str) -> list[str]:
    """Возвращает список тегов для тендера по его названию."""
    n = _norm(name)
    result = []
    for tag, data in TAGS_DEF.items():
        if tag == "Услуги":
            continue
        for kw in data["keywords"]:
            if _norm(kw) in n:
                result.append(tag)
                break
    # Услуги — только если нет других тегов
    if not result:
        for kw in TAGS_DEF["Услуги"]["keywords"]:
            if _norm(kw) in n:
                result.append("Услуги")
                break
    return result


def is_relevant(name: str, tags: list[str]) -> bool:
    """True если тендер связан со строительством или промышленным оборудованием."""
    if not name:
        return False
    n = _norm(name)
    # Нерелевантные теги = только Услуги без конкретики
    relevant_tags = [t for t in tags if t != "Услуги"]
    if relevant_tags:
        return True
    # Проверяем стоп-слова
    for sw in _STOP_WORDS:
        if _norm(sw) in n:
            return False
    # Без тегов и без стоп-слов — оставляем (неопределённость → не фильтруем)
    return True


