def is_construction(name: str) -> bool:
    """True, если название тендера относится к строительству/подряду (лист 2)."""
    if not name:
        return False
    n = _norm(name)
    for kw in CONSTRUCTION_KEYWORDS:
        if _norm(kw) in n:
            return True
    return False


# ── Сопоставление с фразами номенклатуры ──────────────────────────────────
#
# Мягкий keyword-фильтр (parser_runner.apply_keyword_filter) оставляет из
# выдачи поиска по фразе только лоты, совпадающие с ВКЛЮЧЁННЫМИ фразами
# профиля (keywords.json).

# Кавычки и прочую пунктуацию заменяем пробелом, а не удаляем: «„НШ 1-15“» не
# должен склеивать кавычку со следующим словом. Скобки и запятые попали сюда по
# живым названиям: «Мониторинг цен (подшипник на ось 2,1х3,6)» — слово
# «(подшипник» не совпадало ни с чем, и такие позиции из «мониторинга цен»
# терялись (найдено 01.09.2026). Дефис НЕ трогаем — он значащий в «НШ 1-15».
_NOM_QUOTES = r""""«»„“”'`(),.;:!?/\[]{}<>|*—–_№"""
_NOM_WS_RE = re.compile(r"\s+")
_NOM_ZCH_RE = re.compile(r"(?<![0-9a-zа-я])з\s*[/\\]\s*ч(?![0-9a-zа-я])")


def _split_service_hyphen(token: str) -> str:
    """Отделить служебный номер, приклеенный к слову дефисом.

    Закупочные операторы лепят к названию свой номер: «2608-Лента
    транспортерная», «RUZVZ-8260, закупка Флотомашины». Такой токен разбирался
    как составное слово («фильтр-пресс») и требовал, чтобы у фразы тоже было
    две части через дефис, — на живой базе так терялись 59 лотов по конвейерам.

    Разделяем только когда РОВНО ОДНА часть состоит из цифр: «2608-лента» и
    «ruzvz-8260» разъезжаются, а марка «1-15» и составное «фильтр-пресс»
    остаются целыми — их точность держится именно на дефисе.
    """
    if "-" not in token:
        return token
    parts = token.split("-")
    if len(parts) != 2:
        return token
    left, right = parts
    if not left or not right:
        return token
    if left.isdigit() != right.isdigit():
        return f"{left} {right}"
    return token


def _norm_nomenclature(text: str) -> str:
    """lower + ё→е + пунктуация→пробел + схлопывание пробелов (дефис сохраняем)."""
    n = text.lower().replace("ё", "е")
    # «з/ч» и «з\ч» — запчасти; после замены дроби пробелом от них остались бы
    # две буквы, которые совпадают с чем угодно («инв. № З-00002896, ч. 2»).
    n = _NOM_ZCH_RE.sub("зч", n)
    for ch in _NOM_QUOTES:
        n = n.replace(ch, " ")
    n = _NOM_WS_RE.sub(" ", n).strip()
    if "-" in n:
        n = " ".join(_split_service_hyphen(w) for w in n.split(" "))
    return n


def _common_prefix_len(a: str, b: str) -> int:
    i = 0
    limit = min(len(a), len(b))
    while i < limit and a[i] == b[i]:
        i += 1
    return i


@lru_cache(maxsize=300_000)
def _word_matches(phrase_word: str, name_word: str) -> bool:
    """Совпадает ли слово фразы со словом названия.

    Подстрочного сравнения недостаточно: «Клиновая задвижка» обязана
    совпасть с «Задвижки клиновые», а падежные окончания этому мешают. Поэтому слово считается совпавшим,
    если у него со словом названия общий префикс-основа не короче слова
    минус русское окончание (до 3 символов, но не меньше 3).

    Короткие слова (<5 симв., напр. «ПП», «сода») и слова с цифрами («1-15» —
    дефис значащий) сравниваются только на точное равенство: иначе «Пачук»
    совпал бы с «пачкой», а «1-15» с «1-16».

    Составные через дефис сравниваются по частям, и совпасть должны ВСЕ:
    «фильтр-пресс» находится в «фильтр-пресса», но не в «фильтр воздушный» —
    на живых данных 26.08.2026 такая фраза ловила любой фильтр, из 1543 лотов
    совпадало 93 вместо 29.

    Для остальных требуем, чтобы общая основа покрывала оба слова без их
    окончаний (до 3 символов с каждой стороны) и была не короче 5 символов:
    «пластинчатый» ↔ «пластинчатого» проходит, «известь» ↔ «изверженный» нет.

    Результат кэшируется: справочник сравнивает каждый лот с девятью сотнями
    терминов, слова в них повторяются от лота к лоту, и на пересчёте базы
    01.09.2026 эта функция звалась 1,9 млн раз на триста лотов — 26 млн
    проверок «есть ли цифра в слове» внутри. Функция чистая (зависит только
    от двух слов), поэтому кэш безопасен.
    """
    if phrase_word == name_word:
        return True
    if any(c.isdigit() for c in phrase_word) or any(c.isdigit() for c in name_word):
        return False
    if "-" in phrase_word or "-" in name_word:
        left = phrase_word.split("-")
        right = name_word.split("-")
        if len(left) != len(right) or len(left) == 1:
            return False
        return all(_word_matches(a, b) for a, b in zip(left, right))
    if len(phrase_word) < 5 or len(name_word) < 5:
        return False
    common = _common_prefix_len(phrase_word, name_word)
    return (
        common >= 5 and common >= len(phrase_word) - 3 and common >= len(name_word) - 3
    )


def name_words(name: str) -> list[str]:
    """Слова названия лота, готовые к сравнению. Пусто — если сравнивать нечем."""
    if not isinstance(name, str):
        return []
    norm = _norm_nomenclature(name)
    return norm.split(" ") if norm else []


def prepare_terms(phrases: Iterable[str]) -> list[tuple[str, list[str]]]:
    """Разобрать фразы один раз: (исходная фраза, её нормализованные слова).

    Профиль сравнивает каждый лот с девятью сотнями терминов справочника, и
    без этой подготовки каждая фраза нормализуется заново на каждом лоте:
    на живой базе 01.09.2026 это 26 тысяч разборов на четыреста лотов и
    сорок секунд на полный пересчёт. Разбор не зависит от лота — значит его
    место при загрузке справочника, а не в горячем цикле.
    """
    prepared: list[tuple[str, list[str]]] = []
    for phrase in phrases or ():
        if not isinstance(phrase, str):
            continue
        norm = _norm_nomenclature(phrase)
        if norm:
            prepared.append((phrase, norm.split(" ")))
    return prepared


def hits_prepared(
    words: list[str], prepared: Iterable[tuple[str, list[str]]]
) -> list[str]:
    """То же, что nomenclature_hits, но на готовых словах и терминах."""
    if not words:
        return []
    hits: list[str] = []
    for phrase, term_words in prepared:
        if all(any(_word_matches(w, nw) for nw in words) for w in term_words):
            hits.append(phrase)
    return hits


def nomenclature_hits(name: str, phrases: Iterable[str]) -> list[str]:
    """Список фраз из ``phrases``, совпавших с названием лота ``name``.

    Фраза совпала, если ВСЕ её слова нашлись среди слов названия (порядок
    слов не важен, окончания игнорируются — см. _word_matches). Пустое имя,
    None или не-строка → пустой список.
    """
    return hits_prepared(name_words(name), prepare_terms(phrases))


def matches_nomenclature(name: str, phrases: Iterable[str]) -> bool:
    """True, если название лота совпадает хотя бы с одной фразой номенклатуры."""
    return bool(nomenclature_hits(name, phrases))


