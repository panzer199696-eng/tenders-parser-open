_TAG_SCORES = {
    "Горнодобыча": 20,
    "СМР": 15,
    "Оборудование": 15,
    "Металлопрокат": 10,
    "КИП и А": 10,
    "Запчасти": 8,
    "Материалы": 8,
    "ГСМ": 5,
    "Услуги": 0,
}


def score_tender(tender: dict) -> int:
    """
    Оценка перспективности тендера (0..100) БЕЗ опоры на цену.

    В выдаче части площадок цены нет (она только в карточке лота), поэтому скоринг строится
    на содержательных признаках:
      • теги (профильность закупки) — основной вклад;
      • признак «строительство/подряд» — целевая категория ПТО (+бонус);
      • близость дедлайна (актуально до) — успеть подать (оптимум 7–21 день);
      • соответствие организатора искомой компании (organizer_match) — +бонус.

    Если в будущем сумма появится (напр. из карточки) — учитываем как доп.бонус,
    но скоринг не обнуляется при её отсутствии.

    Формула (документирована в отчёте):
        score = Σ tag_scores + construction_bonus(20) + deadline_bonus(до 15)
                + organizer_bonus(10) + price_bonus(до 20, если цена есть)
    Порог promising = 30 (подобран так, чтобы лист не был пуст и не помечал всё).
    """
    s = 0

    # 1. Теги (основной вклад)
    for tag in tender.get("tags", []):
        s += _TAG_SCORES.get(tag, 0)

    # 2. Строительство/подряд — целевая категория
    if tender.get("construction") or is_construction(tender.get("name", "")):
        s += 20

    # 3. Близость дедлайна (оптимум: 7–21 день)
    dl = tender.get("date_deadline") or tender.get("date_to_display", "")
    dl_date = _parse_deadline(dl)
    if dl_date is not None:
        days = (dl_date - today_msk()).days
        if 7 <= days <= 21:
            s += 15
        elif 3 <= days < 7:
            s += 12
        elif 0 <= days < 3:
            s += 6
        elif 21 < days <= 45:
            s += 8

    # 4. Организатор соответствует искомой компании (профильный лот)
    if tender.get("organizer_match"):
        s += 10

    # 5. Сумма — опциональный бонус, если когда-нибудь появится
    amount = tender.get("sum")
    if amount is not None:
        try:
            amount = float(amount)
            if amount >= 50_000_000:
                s += 20
            elif amount >= 10_000_000:
                s += 15
            elif amount >= 1_000_000:
                s += 10
            elif amount >= 100_000:
                s += 5
        except (ValueError, TypeError):
            pass

    return min(s, 100)


def classify(tender: dict) -> dict:
    """Добавляет в тендер поля: tags, relevant, construction, score, promising."""
    name = tender.get("name", "")
    tags = assign_tags(name)
    relevant = is_relevant(name, tags)
    construction = is_construction(name)
    enriched = {**tender, "tags": tags, "construction": construction}
    sc = score_tender(enriched)
    return {
        **enriched,
        "relevant": relevant,
        "score": sc,
        # Порог снижен до 30: цены нет → скоринг строится на тегах/дедлайне/
        # признаке строительства, абсолютные значения ниже прежних. 30 даёт
        # непустой, но осмысленный лист «перспективных».
        "promising": sc >= 30,
    }
