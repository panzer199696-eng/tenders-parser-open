def _parse_deadline(value: str) -> date | None:
    """День окончания подачи; None — срока нет или не понят (src/dates.py)."""
    from ..dates import deadline_date

    return deadline_date(value)


def is_active(tender: dict, today: date | None = None) -> bool:
    """
    True, если тендер ещё НЕ завершён на дату запуска парсера.

    Правило: date_deadline >= today. Если дедлайн не распарсился, пуст или
    'Не указана' — тендер ОСТАВЛЯЕМ (не теряем из-за неизвестной даты).
    """
    # «Сегодня» — московское: ночной сбор в 03:00 по ПК (UTC+7) — это 23:00
    # МСК, и по дате ПК лоты «до конца сегодня» отсекались (Г2, 16.10.2026).
    if today is None:
        today = today_msk()
    dl = _parse_deadline(tender.get("date_deadline", ""))
    if dl is None:
        return True
    return dl >= today


